class Encoder(nn.Module):

    def __init__(
        self,
        src_vocab_size,
        emb_dim,
        hid_dim,
        pad_idx=PAD
    ):

        super().__init__()

        self.embedding = nn.Embedding(
            src_vocab_size,
            emb_dim,
            padding_idx=pad_idx
        )

        self.gru = nn.GRU(
            emb_dim,
            hid_dim,
            batch_first=True,
            bidirectional=True
        )

        self.fc = nn.Linear(
            hid_dim,
            hid_dim
        )

    def forward(self, src, src_lengths):

        embedded = self.embedding(src)

        packed = pack_padded_sequence(
            embedded,
            src_lengths.cpu(),
            batch_first=True,
            enforce_sorted=False
        )

        packed_outputs, hidden = self.gru(packed)

        outputs, _ = pad_packed_sequence(
            packed_outputs,
            batch_first=True,
            total_length=src.size(1)
        )

        backward_final = hidden[1]

        initial_decoder_state = torch.tanh(
            self.fc(backward_final)
        )

        return outputs, initial_decoder_state

class BahdanauAttention(nn.Module):

    def __init__(
        self,
        enc_dim,
        dec_dim,
        attn_dim
    ):

        super().__init__()

        self.W = nn.Linear(
            dec_dim,
            attn_dim,
            bias=False
        )

        self.U = nn.Linear(
            enc_dim,
            attn_dim,
            bias=False
        )

        self.v = nn.Linear(
            attn_dim,
            1,
            bias=False
        )

    def forward(
        self,
        decoder_state,
        encoder_outputs,
        src_mask
    ):

        query = self.W(
            decoder_state
        ).unsqueeze(1)

        keys = self.U(encoder_outputs)

        energy = torch.tanh(
            query + keys
        )

        scores = self.v(
            energy
        ).squeeze(-1)

        scores = scores.masked_fill(
            src_mask == 0,
            -1e9
        )

        attention_weights = F.softmax(
            scores,
            dim=1
        )

        context = torch.bmm(
            attention_weights.unsqueeze(1),
            encoder_outputs
        ).squeeze(1)

        return context, attention_weights

class Decoder(nn.Module):

    def __init__(
        self,
        tgt_vocab_size,
        emb_dim,
        enc_dim,
        hid_dim,
        attn_dim,
        maxout_dim,
        pad_idx=PAD
    ):

        super().__init__()

        self.embedding = nn.Embedding(
            tgt_vocab_size,
            emb_dim,
            padding_idx=pad_idx
        )

        self.attention = BahdanauAttention(
            enc_dim,
            hid_dim,
            attn_dim
        )

        self.gru = nn.GRUCell(
            emb_dim + enc_dim,
            hid_dim
        )

        self.Wo = nn.Linear(
            hid_dim + emb_dim + enc_dim,
            maxout_dim * 2
        )

        self.output = nn.Linear(
            maxout_dim,
            tgt_vocab_size
        )

        self.maxout_dim = maxout_dim

    def forward(
        self,
        previous_token,
        previous_state,
        encoder_outputs,
        src_mask
    ):

        embedded = self.embedding(
            previous_token
        )

        context, attention_weights = self.attention(
            previous_state,
            encoder_outputs,
            src_mask
        )

        gru_input = torch.cat(
            [embedded, context],
            dim=1
        )

        new_state = self.gru(
            gru_input,
            previous_state
        )

        combined = torch.cat(
            [new_state, embedded, context],
            dim=1
        )

        output = self.Wo(combined)

        output = output.view(
            output.size(0),
            self.maxout_dim,
            2
        )

        output = output.max(dim=2).values

        logits = self.output(output)

        return logits, new_state, attention_weights

class RNNsearch(nn.Module):

    def __init__(
        self,
        src_vocab_size,
        tgt_vocab_size,
        emb_dim=128,
        hid_dim=256,
        attn_dim=128,
        maxout_dim=128
    ):

        super().__init__()

        self.encoder = Encoder(
            src_vocab_size,
            emb_dim,
            hid_dim
        )

        self.decoder = Decoder(
            tgt_vocab_size,
            emb_dim,
            2 * hid_dim,
            hid_dim,
            attn_dim,
            maxout_dim
        )

    def forward(
        self,
        src,
        src_lengths,
        tgt,
        teacher_forcing=1.0
    ):

        encoder_outputs, decoder_state = self.encoder(
            src,
            src_lengths
        )

        src_mask = (src != PAD)

        previous_token = tgt[:, 0]

        all_logits = []

        for t in range(1, tgt.size(1)):

            logits, decoder_state, attention_weights = self.decoder(
                previous_token,
                decoder_state,
                encoder_outputs,
                src_mask
            )

            all_logits.append(logits)

            if random.random() < teacher_forcing:

                previous_token = tgt[:, t]

            else:

                previous_token = logits.argmax(dim=1)

        return torch.stack(all_logits, dim=1)

def train_step(
    model,
    optimizer,
    src,
    src_lengths,
    tgt
):

    model.train()

    optimizer.zero_grad()

    logits = model(
        src,
        src_lengths,
        tgt,
        teacher_forcing=1.0
    )

    target = tgt[:, 1:]

    loss = F.cross_entropy(
        logits.reshape(-1, logits.size(-1)),
        target.reshape(-1),
        ignore_index=PAD
    )

    loss.backward()

    torch.nn.utils.clip_grad_norm_(
        model.parameters(),
        max_norm=1.0
    )

    optimizer.step()

    return loss.item()

@torch.no_grad()
def evaluate_loss(model, loader):

    model.eval()

    total_loss = 0.0
    total_tokens = 0
    correct_tokens = 0

    for src, src_lengths, tgt in loader:

        src = src.to(device)
        src_lengths = src_lengths.to(device)
        tgt = tgt.to(device)

        logits = model(
            src,
            src_lengths,
            tgt,
            teacher_forcing=1.0
        )

        target = tgt[:, 1:]

        loss = F.cross_entropy(
            logits.reshape(-1, logits.size(-1)),
            target.reshape(-1),
            ignore_index=PAD,
            reduction="sum"
        )

        total_loss += loss.item()

        predictions = logits.argmax(dim=-1)

        mask = (target != PAD)

        correct_tokens += (
            (predictions == target) & mask
        ).sum().item()

        total_tokens += mask.sum().item()

    average_loss = total_loss / total_tokens

    accuracy = (
        100.0 * correct_tokens / total_tokens
    )

    return average_loss, accuracy

