@torch.no_grad()
def translate_attention(model, sentence):

    model.eval()

    tokens = tokenize(sentence)

    src_ids = [
        src_vocab.get(token, UNK)
        for token in tokens
    ]

    src = torch.tensor(
        [src_ids],
        dtype=torch.long
    ).to(device)

    src_lengths = torch.tensor(
        [len(src_ids)],
        dtype=torch.long
    )

    encoder_outputs, decoder_state = model.encoder(
        src,
        src_lengths
    )

    src_mask = (src != PAD)

    previous_token = torch.tensor(
        [SOS],
        dtype=torch.long
    ).to(device)

    generated_ids = []
    attention_list = []

    for _ in range(50):

        logits, decoder_state, attention_weights = model.decoder(
            previous_token,
            decoder_state,
            encoder_outputs,
            src_mask
        )

        predicted_token = logits.argmax(dim=1)

        predicted_id = predicted_token.item()

        if predicted_id == EOS:
            break

        generated_ids.append(predicted_id)

        attention_list.append(
            attention_weights.squeeze(0).cpu().numpy()
        )

        previous_token = predicted_token

    translated_words = [
        tgt_id2word.get(idx, "<unk>")
        for idx in generated_ids
    ]

    translation = " ".join(translated_words)

    if attention_list:
        attention_matrix = np.stack(attention_list)
    else:
        attention_matrix = np.empty((0, len(tokens)))

    return translation, tokens, translated_words, attention_matrix

