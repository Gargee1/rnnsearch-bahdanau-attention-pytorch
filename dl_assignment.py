class TranslationDataset(Dataset):

    def __init__(self, split, src_vocab, tgt_vocab):

        self.data = split
        self.src_vocab = src_vocab
        self.tgt_vocab = tgt_vocab

    def __len__(self):

        return len(self.data)

    def __getitem__(self, idx):

        example = self.data[idx]

        src_tokens = tokenize(example["en"])

        src_ids = [
            self.src_vocab.get(token, UNK)
            for token in src_tokens
        ]

        tgt_tokens = tokenize(example["de"])

        tgt_ids = (
            [SOS]
            + [
                self.tgt_vocab.get(token, UNK)
                for token in tgt_tokens
            ]
            + [EOS]
        )

        return (
            torch.tensor(src_ids, dtype=torch.long),
            torch.tensor(tgt_ids, dtype=torch.long)
        )


def collate_fn(batch):

    src_batch, tgt_batch = zip(*batch)

    src_lengths = torch.tensor(
        [len(src) for src in src_batch],
        dtype=torch.long
    )

    src_padded = pad_sequence(
        src_batch,
        batch_first=True,
        padding_value=PAD
    )

    tgt_padded = pad_sequence(
        tgt_batch,
        batch_first=True,
        padding_value=PAD
    )

    return src_padded, src_lengths, tgt_padded


